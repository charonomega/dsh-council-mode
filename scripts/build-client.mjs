/** Build the single-file browser bundle for Council Mode. */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLIS, CLI_IDS, ROLES } from '../lib/catalog.js';
import { AVATARS } from '../client-src/avatar-data.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const read = (path) => readFile(resolve(root, path), 'utf8');

const pkg = JSON.parse(await read('package.json'));
const css = await read('client-src/council.css');
const room = stripExports(await read('lib/client-room.js'));
const locales = stripExports(await read('client-src/locales.js'));
const state = stripExports(await read('client-src/state.js'));
const components = stripExports(await read('client-src/components.js'));
const apply = stripExports(await read('client-src/apply.js'));

const clientRoles = ROLES.map(({ id, name, summary, readOnly }) => ({ id, name, summary, readOnly }));
const prelude = [
  `const CLIS = ${JSON.stringify(CLIS)};`,
  `const CLI_IDS = ${JSON.stringify(CLI_IDS)};`,
  `const ROLES = ${JSON.stringify(clientRoles)};`,
  `const AVATARS = ${JSON.stringify(AVATARS)};`,
  `const CSS_TEXT = ${JSON.stringify(css)};`,
].join('\n');

const wrapper = `// Generated by scripts/build-client.mjs. Do not edit by hand.
// Source: client-src/*.js, lib/client-room.js, lib/catalog.js, scripts/prepare-avatars.py.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    const React = require("react");
    const h = React.createElement;

${prelude}

${room}

${locales}

${state}

${components}

${apply}

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`;

await writeFile(resolve(root, 'client.js'), wrapper, 'utf8');
console.log(`wrote client.js (${Buffer.byteLength(wrapper)} bytes)`);

function stripExports(source) {
  const stripped = source.replace(/^export\s+/gm, '');
  if (/^\s*import\s/m.test(stripped) || /^\s*export\s/m.test(stripped)) {
    throw new Error('client sources must be plain snippets without import/export statements');
  }
  return stripped;
}
