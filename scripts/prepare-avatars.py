"""Prepare council avatar assets.

Copies the CLI brand marks shipped with the installed dsh-cliworker-now
package, trims transparent padding, fits each mark onto a 72x72 transparent
canvas, and emits a JS data-URL module used by the browser bundle.
"""

from __future__ import annotations

import base64
import io
import os
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(
    os.environ.get(
        "CLIWORKER_ASSETS",
        str(Path.home() / ".dsh" / "profiles" / "desktop" / "node_modules" / "dsh-cliworker-now" / "lib" / "types" / "client" / "assets"),
    )
)
OUT = ROOT / "assets" / "avatars"
DATA_OUT = ROOT / "client-src" / "avatar-data.js"
SIZE = 72

FILES = {
    "antigravity.png": "antigravity",
    "claude-code.png": "claude",
    "codex.png": "codex",
    "grok.png": "grok",
    "hermes.png": "hermes",
    "kimi-dark.png": "kimi-dark",
    "kimi-light.png": "kimi-light",
    "mimo-code.png": "mimo",
    "omp.png": "omp",
    "opencode.png": "opencode",
    "pi.png": "pi",
    "qoder.png": "qoder",
    "zcode.png": "zcode",
}


def render(source: Path) -> Image.Image:
    image = Image.open(source).convert("RGBA")
    bbox = image.getbbox()
    if bbox is not None:
        image = image.crop(bbox)
    image = ImageOps.contain(image, (SIZE - 8, SIZE - 8), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    canvas.alpha_composite(image, ((SIZE - image.width) // 2, (SIZE - image.height) // 2))
    return canvas


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    DATA_OUT.parent.mkdir(parents=True, exist_ok=True)
    entries: list[str] = []
    for filename, key in FILES.items():
        source = SOURCE / filename
        if not source.exists():
            print(f"skip missing {source}")
            continue
        image = render(source)
        target = OUT / f"{key}.png"
        image.save(target, "PNG", optimize=True)
        buffer = io.BytesIO()
        image.save(buffer, "PNG", optimize=True)
        encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
        entries.append(f'  {key!r}: "data:image/png;base64,{encoded}"')
        print(f"{key:12} {target.stat().st_size:6d} bytes  data {len(encoded):6d} chars")

    module = (
        "// Generated by scripts/prepare-avatars.py. Do not edit by hand.\n"
        "// Source: dsh-cliworker-now client assets (MIT); CLI marks remain the\n"
        "// property of their respective owners. See NOTICE.\n"
        "export const AVATARS = {\n" + ",\n".join(entries) + "\n};\n"
    )
    DATA_OUT.write_text(module, encoding="utf-8")
    print(f"wrote {DATA_OUT}")


if __name__ == "__main__":
    main()
